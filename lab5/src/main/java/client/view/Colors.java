package client.view;

import java.awt.*;

public class Colors {
    static final Color messageColor = Color.decode("#E4F0F7");
    static final Color systemMessageColor = Color.decode("#FFF9C4");
    static final Color BackgroundColor = Color.decode("#322F41");

    static public Color getMessageColor() {
        return messageColor;
    }
    static public Color getSystemMessageColor() {
        return systemMessageColor;
    }
    static public Color getBackgroundColor() {
        return BackgroundColor;
    }
}
